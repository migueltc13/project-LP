from .program import check_program
from .labels import check_labels
from .loops import check_loops
from .variables import check_variables, SemanticInfo


def semantic_checks(parser, ast) -> SemanticInfo:
    """
    Run all semantic checks on the parsed Fortran 77 source code.

    This includes:

    1. Program unit checks
    2. Label checks
    3. Loop checks
    4. Variable checks
    TODO 5. Function and subroutine checks
    TODO 6. Type checks
    TODO Maybe 7. Control flow checks

    Arguments:
        parser: The parser object containing the parsed source code and related
                information.
        ast: The AST generated by the parser.

    Returns:
        SemanticInfo: Information collected during semantic analysis, including
                      variable metadata used later by code generation.
    """
    check_program(parser)
    check_labels(parser)
    check_loops(parser)
    semantic_info = check_variables(parser, ast)

    return semantic_info
